struct SplinePointFieldRefs
{
    Vector3Field* Location = nullptr;
    Vector3Field* Rotation = nullptr;
    Vector3Field* Scale = nullptr;
    Vector3Field* TangentIn = nullptr;
    Vector3Field* TangentOut = nullptr;
    FloatField* Radius = nullptr;
    FloatField* Roll = nullptr;
};

static void AddSplineInfoCard(UIElement* parent, uint32 pointCount, uint32 segmentCount,
                              const std::optional<float32>& worldLength)
{
    UIElement* row = InspectorUI::AddRow(parent);
    row->AddClass("inspector-guide-row");
    InspectorUI::AddLabel(row, "Spline Info",
        "Summary of the spline geometry generated by its control points.");
    UIElement* fieldContainer = InspectorUI::AddFieldContainer(row);
    fieldContainer->AddClass("inspector-guide-field");

    std::string summary = "Points: " + std::to_string(pointCount) + "\n" +
                          "Segments: " + std::to_string(segmentCount);
    if (worldLength)
    {
        char buf[64];
        std::snprintf(buf, sizeof(buf), "\nLength: %.1f m", *worldLength);
        summary += buf;
    }

    fieldContainer->AddChild(std::make_unique<EditorUI::CollapsibleInfoCard>(summary));
}

class SplineInspectorLiveRefresh final : public UIElement
{
public:
    SplineInspectorLiveRefresh(EditorChangeNotifications* notifications,
                               ECS::World* world,
                               ECS::EntityHandle entity,
                               SplineECS::SplineService* splineService,
                               SplineECS::SplineHandle handle,
                               std::shared_ptr<std::vector<SplinePointFieldRefs>> pointFields)
        : m_Notifications(notifications),
          m_World(world),
          m_Entity(entity),
          m_SplineService(splineService),
          m_Handle(handle),
          m_PointFields(std::move(pointFields))
    {
        InlineOverrides().Set(Style::Display, DisplayMode::None);
        if (!m_Notifications || !m_World || !m_Entity.IsValid())
            return;

        const ECS::ComponentTypeId splineType = ECS::GetComponentTypeId<Components::SplineComponent>();
        m_Subscription = m_Notifications->SubscribeComponentChanged(
            [this, splineType](const EditorChangeNotifications::ComponentChangedEvent& ev)
            {
                if (ev.world != m_World || ev.entity != m_Entity || ev.componentType != splineType)
                    return;
                if (ev.kind != EditorChangeNotifications::ChangeKind::Preview &&
                    ev.kind != EditorChangeNotifications::ChangeKind::Commit &&
                    ev.kind != EditorChangeNotifications::ChangeKind::UndoRedo)
                {
                    return;
                }

                RefreshPointFields();
            });
    }

    ~SplineInspectorLiveRefresh() override
    {
        if (m_Notifications && m_Subscription)
            m_Notifications->Unsubscribe(m_Subscription);
    }

private:
    static Rendering::Vector3 ToUiVector(const Mathematics::Vector3& v)
    {
        return Rendering::Vector3(v.x, v.y, v.z);
    }

    void RefreshPointFields()
    {
        if (!m_PointFields || !m_SplineService)
            return;

        const auto* data = m_SplineService->GetSplineData(m_Handle);
        if (!data)
            return;

        const size_t count = std::min(m_PointFields->size(), data->Points.size());
        for (size_t i = 0; i < count; ++i)
        {
            const auto& point = data->Points[i];
            const SplinePointFieldRefs& fields = (*m_PointFields)[i];
            if (fields.Location)
                fields.Location->SetValue(ToUiVector(point.Position));
            if (fields.Rotation)
                fields.Rotation->SetValue(ToUiVector(point.Rotation));
            if (fields.Scale)
                fields.Scale->SetValue(ToUiVector(point.Scale));
            if (fields.TangentIn)
                fields.TangentIn->SetValue(ToUiVector(point.TangentIn));
            if (fields.TangentOut)
                fields.TangentOut->SetValue(ToUiVector(point.TangentOut));
            if (fields.Radius)
                fields.Radius->SetValue(point.Radius);
            if (fields.Roll)
                fields.Roll->SetValue(point.Roll);
        }
    }

    EditorChangeNotifications* m_Notifications = nullptr;
    ECS::World* m_World = nullptr;
    ECS::EntityHandle m_Entity{};
    SplineECS::SplineService* m_SplineService = nullptr;
    SplineECS::SplineHandle m_Handle{};
    std::shared_ptr<std::vector<SplinePointFieldRefs>> m_PointFields;
    EditorChangeNotifications::SubscriptionToken m_Subscription{};
};

static FloatField* AddSplineFloatRowWithUndo(UIElement* parent,
                                             const std::string& rowLabel,
                                             float initialValue,
                                             SplineECS::SplineService* splineService,
                                             SplineECS::SplineHandle splineHandle,
                                             ECS::World* world,
                                             ECS::EntityHandle entity,
                                             EditorChangeNotifications* notifications,
                                             UndoRedoService* undo,
                                             const std::string& undoEditName,
                                             const std::function<void(GameEngine::Spline::SplineData*, float v)>& mutate,
                                             float defaultResetValue,
                                             const char* tooltip)
{
    using namespace InspectorDrag;
    using OptEdit = std::optional<UndoRedoService::InteractiveEdit>;
    auto editPtr = std::make_shared<OptEdit>();

    return AddFloatRowWithDrag(
        parent,
        rowLabel,
        initialValue,
        [splineService, splineHandle, world, entity, notifications, undo, mutate, editPtr,
         undoEditName](float v)
        {
            if (!splineService)
                return;

            if (!editPtr->has_value() && undo)
            {
                UndoRedoService::InteractiveEdit ie =
                    undo->BeginInteractiveEdit(undoEditName,
                        MakeSplineEditableSnapshotTarget(splineService, splineHandle, world, entity, notifications,
                                                         undoEditName));
                if (!ie)
                    return;
                editPtr->emplace(std::move(ie));
            }

            auto* data = splineService->GetSplineData(splineHandle);
            if (!data)
                return;

            mutate(data, v);
            data->MarkDirty();
            splineService->RebuildCache(splineHandle);

            if (editPtr->has_value() && static_cast<bool>(editPtr->value()))
            {
                editPtr->value().Preview([splineService, splineHandle]() {
                    splineService->RebuildCache(splineHandle);
                });
            }
            else if (notifications)
            {
                notifications->NotifyComponentChange<Components::SplineComponent>(
                    world, entity, EditorChangeNotifications::ChangeKind::Preview);
            }
        },
        [splineService, splineHandle, world, entity, notifications, undo, mutate, editPtr,
         undoEditName](float v)
        {
            if (!splineService)
                return;

            auto* data = splineService->GetSplineData(splineHandle);
            if (!data)
                return;

            if (editPtr->has_value() && static_cast<bool>(editPtr->value()))
            {
                mutate(data, v);
                data->MarkDirty();
                splineService->RebuildCache(splineHandle);
                editPtr->value().Commit();
                editPtr->reset();
            }
            else
            {
                CommitSplineDataOneShot(splineService, splineHandle, world, entity, notifications, undo, undoEditName,
                                    [&](GameEngine::Spline::SplineData* d) {
                                        mutate(d, v);
                                    });
            }
        },
        defaultResetValue,
        tooltip);
}

static Vector3Field* AddSplineVector3RowWithUndo(
    UIElement* parent,
    const std::string& rowLabel,
    const Mathematics::Vector3& initialValue,
    SplineECS::SplineService* splineService,
    SplineECS::SplineHandle splineHandle,
    ECS::World* world,
    ECS::EntityHandle entity,
    EditorChangeNotifications* notifications,
    UndoRedoService* undo,
    const std::string& undoEditName,
    const std::function<void(GameEngine::Spline::SplineData*, const Mathematics::Vector3&)>& mutate,
    const Mathematics::Vector3& defaultResetValue,
    const char* tooltip)
{
    using OptEdit = std::optional<UndoRedoService::InteractiveEdit>;
    auto editPtr = std::make_shared<OptEdit>();

    UIElement* row = InspectorUI::AddRow(parent);
    InspectorUI::AddLabel(row, rowLabel, tooltip);
    UIElement* fieldContainer = InspectorUI::AddFieldContainer(row);

    auto field = std::make_unique<Vector3Field>();
    field->AddClass("inspector-vector3");
    field->SetDefaultValue(Rendering::Vector3(defaultResetValue.x, defaultResetValue.y, defaultResetValue.z));
    field->SetValue(Rendering::Vector3(initialValue.x, initialValue.y, initialValue.z));
    Vector3Field* raw = field.get();

    raw->SetOnValueChanging(
        [splineService, splineHandle, world, entity, notifications, undo, mutate, editPtr,
         undoEditName](const Rendering::Vector3& v)
        {
            if (!splineService)
                return;

            if (!editPtr->has_value() && undo)
            {
                UndoRedoService::InteractiveEdit ie =
                    undo->BeginInteractiveEdit(undoEditName,
                        MakeSplineEditableSnapshotTarget(splineService, splineHandle, world, entity, notifications,
                                                         undoEditName));
                if (!ie)
                    return;
                editPtr->emplace(std::move(ie));
            }

            auto* data = splineService->GetSplineData(splineHandle);
            if (!data)
                return;

            mutate(data, Mathematics::Vector3(v.x, v.y, v.z));
            data->MarkDirty();
            splineService->RebuildCache(splineHandle);

            if (editPtr->has_value() && static_cast<bool>(editPtr->value()))
            {
                editPtr->value().Preview([splineService, splineHandle]() {
                    splineService->RebuildCache(splineHandle);
                });
            }
            else if (notifications)
            {
                notifications->NotifyComponentChange<Components::SplineComponent>(
                    world, entity, EditorChangeNotifications::ChangeKind::Preview);
            }
        });

    raw->SetOnValueChanged(
        [splineService, splineHandle, world, entity, notifications, undo, mutate, editPtr,
         undoEditName](const Rendering::Vector3& v)
        {
            if (!splineService)
                return;

            auto* data = splineService->GetSplineData(splineHandle);
            if (!data)
                return;

            const Mathematics::Vector3 value(v.x, v.y, v.z);
            if (editPtr->has_value() && static_cast<bool>(editPtr->value()))
            {
                mutate(data, value);
                data->MarkDirty();
                splineService->RebuildCache(splineHandle);
                editPtr->value().Commit();
                editPtr->reset();
            }
            else
            {
                CommitSplineDataOneShot(splineService, splineHandle, world, entity, notifications, undo, undoEditName,
                                    [&](GameEngine::Spline::SplineData* d) {
                                        mutate(d, value);
                                    });
            }
        });

    fieldContainer->AddChild(std::move(field));
    return raw;
}

void SelectSplineKnot(ECS::World& world, ECS::EntityHandle entity, uint32 pointIndex)
{
    const auto state = Editor::SceneTools::AcquireSplineInteractionState(world);
    auto& selection = state->Selection();
    const int32 index = static_cast<int32>(pointIndex);
    selection.Entity = entity;
    selection.PointIndex = index;
    selection.Kind = 1;
    selection.KnotIndices = {index};
    selection.Controls = {{entity, index, 1}};
}

int32 GetSelectedSplineKnot(ECS::World& world, ECS::EntityHandle entity, uint32 pointCount)
{
    const auto state = Editor::SceneTools::AcquireSplineInteractionState(world);
    auto& selection = state->Selection();
    int32 index = -1;
    if (!selection.Controls.empty())
    {
        const auto& active = selection.Controls.back();
        if (active.Entity == entity && active.Kind != 0)
            index = active.PointIndex;
    }
    else if (selection.Entity == entity && selection.Kind != 0)
    {
        index = selection.PointIndex;
    }

    if (index < 0 || static_cast<uint32>(index) >= pointCount)
        return -1;
    return index;
}

std::string FormatSelectedSplineKnotLabel(int32 selected, uint32 pointCount)
{
    if (selected < 0)
        return "None";
    return "Point " + std::to_string(selected) + " / " + std::to_string(pointCount - 1u);
}

struct ResamplePreviewState
{
    std::optional<UndoRedoService::InteractiveEdit> Edit;
    // Entity-local frames from SampleUniform — the authoritative resample
    // source, carrying every interpolated per-point channel.
    std::vector<Spline::SplineFrame> SourceFrames;
    // The same positions in world space when the entity has a WorldTransform:
    // simplification tolerance is measured in world units.
    std::vector<Mathematics::Vector3> MeasurePositions;
    // The control points before the resample, entity-local: what the recipes
    // addressed by point are re-addressed from when it commits.
    std::vector<Mathematics::Vector3> SourcePoints;
};

bool CaptureResampleSource(const Spline::SplineData& data,
                           ECS::World* world,
                           ECS::EntityHandle entity,
                           ResamplePreviewState& state)
{
    if (!data.IsValid())
        return false;

    const uint32 pointCount = static_cast<uint32>(data.Points.size());
    const uint32 sampleCount = std::max(256u, pointCount * 16u);

    state.SourcePoints.clear();
    for (const Spline::SplineControlPoint& point : data.Points)
        state.SourcePoints.push_back(point.Position);

    Spline::SampleUniform(data, sampleCount, state.SourceFrames);
    if (state.SourceFrames.empty())
        return false;

    state.MeasurePositions.clear();
    state.MeasurePositions.reserve(state.SourceFrames.size());

    const Components::WorldTransform* xf =
        (world && entity.IsValid()) ? world->GetComponent<Components::WorldTransform>(entity)
                                    : nullptr;
    if (xf)
    {
        const Mathematics::Matrix4x4 localToWorld = Mathematics::Matrix4x4::FromColumnMajor(xf->matrix);
        for (const auto& frame : state.SourceFrames)
            state.MeasurePositions.push_back(localToWorld.TransformPoint(frame.Position));
    }
    else
    {
        for (const auto& frame : state.SourceFrames)
            state.MeasurePositions.push_back(frame.Position);
    }
    return true;
}

// Deletes one control point as one undo step, with whatever the recipes on
// this spline re-address because the points after it moved down.
void DeleteSplinePoint(SplineECS::SplineService* splineService, SplineECS::SplineHandle handle,
                       ECS::World* w, ECS::EntityHandle e, Editor::EditorChangeNotifications* n,
                       Editor::UndoRedoService* undo, uint32 index)
{
    const auto* before = splineService->GetSplineData(handle);
    if (!before)
        return;
    const uint32 countBefore = static_cast<uint32>(before->Points.size());
    if (undo)
        undo->BeginCompound("Delete Spline Point");
    Editor::SplineUndo::CommitSplineDataOneShot(
        splineService, handle, w, e, n, undo, "Delete Spline Point",
        [index](GameEngine::Spline::SplineData* target) { (void)target->RemovePoint(index); });
    const auto* after = splineService->GetSplineData(handle);
    const uint32 removed[1] = {index};
    const Editor::SplinePointRenumbering renumbering = Editor::SplinePointRenumbering::Removed(
        countBefore, removed, after && after->IsEffectivelyClosed());
    Editor::SplinePointEdited().Invoke({w, e, undo, n, &renumbering});
    if (undo)
        undo->EndCompound();
}

bool ApplyResampleFromSource(Spline::SplineData& data, const ResamplePreviewState& state, float tolerance)
{
    if (state.SourceFrames.size() < 2)
        return false;

    std::vector<uint32> kept;
    Spline::SimplifyPolylineIndices(state.MeasurePositions, tolerance, kept);
    if (kept.size() < 2)
        return false;

    // Kept indices map 1:1 onto the captured frames, so the rebuilt points
    // take their positions AND channels from the same interpolated sample.
    std::vector<Spline::SplineFrame> keptFrames;
    keptFrames.reserve(kept.size());
    for (uint32 index : kept)
        keptFrames.push_back(state.SourceFrames[index]);

    data.ReplacePointsFromFrames(keptFrames);
    return true;
}

