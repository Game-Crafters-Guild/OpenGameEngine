// CMake list entries are quoted; backslashes in Windows paths must be forward
// slashes (or escaped) for CMake. generic_string() already yields forward slashes.
std::string CMakePath(const std::filesystem::path& p)
{
    return p.generic_string();
}

// A CMake list literal ("a;b;c"); the caller quotes it.
std::string CMakeList(const std::vector<std::string>& values)
{
    std::string joined;
    for (const std::string& value : values)
    {
        if (!joined.empty())
            joined += ';';
        joined += value;
    }
    return joined;
}

// Sorted so the generated file depends on the rules and not on the iteration
// order of the set they live in — an unstable list would reconfigure CMake on
// every generate.
std::vector<std::string> SortedIgnoredDirectoryNames(const AssetIgnoreRules& rules)
{
    std::vector<std::string> names(rules.ignoredDirNamesLower.begin(),
                                   rules.ignoredDirNamesLower.end());
    std::sort(names.begin(), names.end());
    return names;
}

// First line of every file this generator writes. Stray cleanup keys on this
// prefix so it can prove a CMakeLists.txt is ours before deleting it — a
// user-authored file never matches.
constexpr std::string_view kGeneratedByMarker =
    "# AUTO-GENERATED by NativeScripting UserProjectGenerator";

// Lexical "is `p` under `base`": the forward-slash remainder, or empty when it is
// not. Case-insensitive on Windows. Lexical on purpose — both paths are built by
// appending to the same configured roots, and Generate may run before they exist.
std::string RelativeUnder(const std::filesystem::path& p, const std::filesystem::path& base)
{
    if (base.empty())
        return {};
    const std::string pStr = p.lexically_normal().generic_string();
    std::string baseStr = base.lexically_normal().generic_string();
    if (baseStr.empty())
        return {};
    if (baseStr.back() != '/')
        baseStr += '/';
    if (pStr.size() <= baseStr.size())
        return {};
#if defined(_WIN32)
    const auto sameChar = [](char a, char b) {
        return std::tolower(static_cast<unsigned char>(a)) == std::tolower(static_cast<unsigned char>(b));
    };
    if (!std::equal(baseStr.begin(), baseStr.end(), pStr.begin(), sameChar))
        return {};
#else
    if (pStr.compare(0, baseStr.size(), baseStr) != 0)
        return {};
#endif
    return pStr.substr(baseStr.size());
}

// The baked last-known-good SDK root in a previously generated file (the
// `set(GAMEENGINE_SDK_DIR "...")` default), or empty when the file has none.
std::string ExtractBakedSdkDefault(const std::string& content)
{
    constexpr std::string_view kKey = "set(GAMEENGINE_SDK_DIR \"";
    const std::size_t start = content.find(kKey);
    if (start == std::string::npos)
        return {};
    const std::size_t valueStart = start + kKey.size();
    const std::size_t valueEnd = content.find('"', valueStart);
    if (valueEnd == std::string::npos)
        return {};
    return content.substr(valueStart, valueEnd - valueStart);
}
