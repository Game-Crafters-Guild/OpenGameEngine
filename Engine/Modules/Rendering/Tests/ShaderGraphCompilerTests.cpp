TEST(ShaderGraphCompilerTests, EveryTagKindRoundTripsSemantically)
{
    const char* source = R"(// Auto-generated. The @sg-* tag block is authoritative.
// The body below is regenerated by the graph editor on save.
//
// @sg-graph     KitchenSink
// @sg-version   3
// @sg-stage     both
// @sg-lighting  StandardPBR
// @sg-variant   GE_USER_SNOW
// @sg-property  Tint float3 default=1,0,0 hint=color public=true
// @sg-property  Power float default=4.0 range=0.5,8.0
// @sg-texture   Albedo "11112222-3333-4444-5555-666677778888" hint=srgb
// @sg-viewport  panX=120.5 panY=-42.25 zoom=1.5
// @sg-futuretag mode=fancy
// @sg-node      c0  type=ColorConstant pos=(-200,140) r=0.08 g=0.28 b=1.0
// @sg-node      out type=SurfaceOutput pos=(1120,160)
// @sg-edge      c0.value -> out.BaseColor
SurfaceOutput EvaluateSurface(SurfaceInput sIn) { return DefaultSurfaceOutput(); }
)";
    const SgParsedFile parsed = ParseShaderGraphSource(source);
    const SgGraphDocument doc = ParseGraphDocumentFromTags(parsed.TagBlock);

    const std::string serialized = SerializeGraphDocumentTags(doc);
    const SgGraphDocument reparsed = ParseGraphDocumentFromTags(serialized);
    ExpectSameGraphDocument(doc, reparsed, "save/reload");
    EXPECT_NE(serialized.find("// @sg-lighting  StandardPBR"), std::string::npos) << serialized;
    EXPECT_NE(serialized.find("// @sg-futuretag mode=fancy"), std::string::npos) << serialized;

    // The loader must not care about tag-line order: nodes after edges, header
    // tags interleaved with node tags.
    const char* reordered = R"(// @sg-edge      c0.value -> out.BaseColor
// @sg-node      out type=SurfaceOutput pos=(1120,160)
// @sg-viewport  panX=120.5 panY=-42.25 zoom=1.5
// @sg-node      c0  type=ColorConstant pos=(-200,140) r=0.08 g=0.28 b=1.0
// @sg-texture   Albedo "11112222-3333-4444-5555-666677778888" hint=srgb
// @sg-property  Tint float3 default=1,0,0 hint=color public=true
// @sg-property  Power float default=4.0 range=0.5,8.0
// @sg-futuretag mode=fancy
// @sg-variant   GE_USER_SNOW
// @sg-lighting  StandardPBR
// @sg-stage     both
// @sg-version   3
// @sg-graph     KitchenSink
)";
    const SgGraphDocument shuffled =
        ParseGraphDocumentFromTags(ParseShaderGraphSource(reordered).TagBlock);
    ExpectSameGraphDocument(doc, shuffled, "reordered tags");
}

