TEST(ShaderGraphCompilerTests, CompareFunctionSelectorsAreDeclaredNamesTheShaderBranchesOn)
{
    /* A node parameter is spliced into the emitted call verbatim, so an enum
       whose values are prose ("greater") compiles to an undefined identifier.
       Every value the editor can store has to be declared in the node source
       AND read by SG_Compare, or the dropdown is decorative at best. */
    const std::string nodeSource = ReadNodeLibrarySource("Utility/Nodes.glsl");
    ASSERT_FALSE(nodeSource.empty());

    for (const char* selector :
         {"SG_COMPARE_GREATER", "SG_COMPARE_LESS", "SG_COMPARE_EQUAL", "SG_COMPARE_NOT_EQUAL",
          "SG_COMPARE_GREATER_EQUAL", "SG_COMPARE_LESS_EQUAL"})
    {
        EXPECT_NE(nodeSource.find(std::string("const float ") + selector + " ="),
                  std::string::npos)
            << selector << " is not declared in Utility/Nodes.glsl";
    }

    // Every selector but the code-0 default has to be branched on by name;
    // the default is the function's fall-through return.
    for (const char* selector :
         {"SG_COMPARE_LESS", "SG_COMPARE_EQUAL", "SG_COMPARE_NOT_EQUAL",
          "SG_COMPARE_GREATER_EQUAL", "SG_COMPARE_LESS_EQUAL"})
    {
        EXPECT_NE(nodeSource.find(std::string("function == ") + selector), std::string::npos)
            << selector << " selects nothing in SG_Compare";
    }
}

