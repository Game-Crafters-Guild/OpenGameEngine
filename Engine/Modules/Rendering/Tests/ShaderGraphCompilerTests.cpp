TEST(ShaderGraphCompilerTests, ParsesQuotedPositionalArgumentAsOneToken)
{
    // A quoted positional keeps its quotes so a consumer can tell "Pulse Speed"
    // (a display name) from a bare flag word; spaces inside it do not split it.
    const auto attrs =
        ParseTagAttributes("// @property float pulseSpeed \"Pulse Speed\" default=2.0 range=0,8 hdr");
    EXPECT_EQ(FindTagAttribute(attrs, "arg0").value_or(""), "float");
    EXPECT_EQ(FindTagAttribute(attrs, "arg1").value_or(""), "pulseSpeed");
    EXPECT_EQ(FindTagAttribute(attrs, "arg2").value_or(""), "\"Pulse Speed\"");
    EXPECT_FALSE(FindTagAttribute(attrs, "arg3").has_value());
    EXPECT_EQ(FindTagAttribute(attrs, "default").value_or(""), "2.0");
    EXPECT_EQ(FindTagAttribute(attrs, "range").value_or(""), "0,8 hdr")
        << "a value still runs to the next key=; the property parser peels trailing flags";
}

TEST(ShaderGraphCompilerTests, QuotedValueIsOneSpanWhateverItContains)
{
    // The value scan must not hunt for the next key= inside a quoted value, and
    // a bare '=' never starts a key. The quotes stay on, as with a quoted
    // positional, so a consumer can tell verbatim text from a bare value.
    const auto attrs = ParseTagAttributes(
        "// @property float emissionScale tooltip=\"scene-linear; 1.0 == 203 nits\" range=0,4");
    EXPECT_EQ(FindTagAttribute(attrs, "tooltip").value_or(""), "\"scene-linear; 1.0 == 203 nits\"");
    EXPECT_EQ(FindTagAttribute(attrs, "range").value_or(""), "0,4");
    EXPECT_FALSE(FindTagAttribute(attrs, "=").has_value());
}
