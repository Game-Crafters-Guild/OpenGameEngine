// The graph-material compile path regenerates <stem>_built.glsl on EVERY
// compile. The shader-edit watcher keys on the file changing, so a rewrite of
// identical bytes re-arms it and the recompile rewrites the file again — a
// self-sustaining recompile loop on an idle editor. "No write when bytes are
// unchanged" is the invariant that breaks the cycle; the watcher-visible
// observable is the file's last-write time, so that is what this test ports.
TEST(ShaderGraphCompilerTests, SaveGraphFileSkipsRewriteWhenContentUnchanged)
{
    namespace fs = std::filesystem;
    const fs::path path =
        fs::temp_directory_path() /
        ("ge_sg_save_norewrite_" +
         std::to_string(::testing::UnitTest::GetInstance()->random_seed()) + ".glsl");
    std::error_code ec;
    fs::remove(path, ec);

    SgGraphDocument doc;
    doc.GraphName = "NoRewrite";
    const std::string body =
        "SurfaceOutput EvaluateSurface(SurfaceInput sIn) { return DefaultSurfaceOutput(); }\n";

    ASSERT_TRUE(SaveGraphFile(path, doc, body));
    const auto firstWrite = fs::last_write_time(path);

    // Sleep past filesystem timestamp granularity so an unwanted rewrite is
    // guaranteed to move the mtime.
    std::this_thread::sleep_for(std::chrono::milliseconds(150));

    ASSERT_TRUE(SaveGraphFile(path, doc, body));
    EXPECT_EQ(fs::last_write_time(path), firstWrite)
        << "identical content was rewritten (mtime advanced) — this re-arms the "
           "shader-edit watcher and loops";

    // Changed content must still be written; prove it by readback, not mtime.
    ASSERT_TRUE(SaveGraphFile(path, doc, body + "// changed\n"));
    std::ifstream in(path);
    const std::string onDisk((std::istreambuf_iterator<char>(in)),
                             std::istreambuf_iterator<char>());
    EXPECT_NE(onDisk.find("// changed"), std::string::npos);

    fs::remove(path, ec);
}

