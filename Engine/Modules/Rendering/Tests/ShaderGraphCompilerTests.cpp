TEST(ShaderGraphCompilerTests, VertexAndSurfaceEntryPointsAreStageGuarded)
{
    SgGraphDocument doc;
    doc.GraphName = "VertexOffset";
    doc.Nodes.push_back({"n0", "FloatConstant", 0.f, 0.f, {{"value", "0.25"}}});
    doc.Nodes.push_back({"out", "SurfaceOutput", 200.f, 0.f, {}});
    doc.Nodes.push_back({"vout", "VertexOutput", 200.f, 200.f, {}});
    doc.Edges.push_back({"n0", "value", "vout", "PositionOffset"});

    const auto library = SgNodeReflector::BuildIndex(GetEngineGraphNodesRoot(), {});
    const auto result = SgGraphCompiler::Compile(doc, library);
    ASSERT_TRUE(result.Success) << (result.Errors.empty() ? "" : result.Errors.front().Message);

    // One file serves both adapters, so each entry point hides from the other stage.
    const size_t surfaceGuard = result.Body.find("#ifndef GE_STAGE_VERTEX");
    const size_t surfaceFn = result.Body.find("SurfaceOutput EvaluateSurface(");
    const size_t vertexGuard = result.Body.find("#ifdef GE_STAGE_VERTEX");
    const size_t vertexFn = result.Body.find("vec3 ModifyVertex(");
    ASSERT_NE(surfaceGuard, std::string::npos);
    ASSERT_NE(surfaceFn, std::string::npos);
    ASSERT_NE(vertexGuard, std::string::npos);
    ASSERT_NE(vertexFn, std::string::npos);
    EXPECT_LT(surfaceGuard, surfaceFn);
    EXPECT_LT(vertexGuard, vertexFn);
    EXPECT_NE(std::find(result.VariantDefines.begin(), result.VariantDefines.end(), "HAS_VERTEX_MODIFIER"),
              result.VariantDefines.end());
}

