// The signature reader must match EXACT function names only — a name that
// merely starts with the base name (SG_SampleTexture2DLOD vs
// SG_SampleTexture2D) is a different function — and must read parameter
// lists that wrap across lines (SG_SampleTexture2D's do).
TEST(ShaderGraphCompilerTests, SignatureReaderMatchesExactNamesAcrossLines)
{
    const std::string source = R"(
void SG_Sample(sampler2D tex, vec2 uv,
               out vec4 rgba, out vec3 rgb)
{
}
void SG_SampleLOD(sampler2D tex, vec2 uv, float lod, out vec3 rgb)
{
}
vec3 MySG_Sample(vec3 x) { return x; }
// a comment mentioning SG_Sample(with, a, paren) must not read as a signature
vec4 SG_Sample(GE_MaterialTexture tex, vec2 uv)
{
    return vec4(0.0);
}
)";
    const auto overloads = ReadTaggedFunctionOverloads(source, "SG_Sample");
    ASSERT_EQ(overloads.size(), 2u)
        << "exactly the two SG_Sample definitions: no LOD leak, no prefixed name, no comment";

    EXPECT_EQ(overloads[0].Inputs.size(), 2u) << "wrapped parameter list read in full";
    EXPECT_EQ(overloads[0].Outputs.size(), 2u);
    EXPECT_EQ(overloads[0].Inputs[0].GlslType, "sampler2D");

    EXPECT_EQ(overloads[1].Inputs.size(), 2u);
    ASSERT_EQ(overloads[1].Outputs.size(), 1u);
    EXPECT_EQ(overloads[1].Outputs[0].Name, "result");
    EXPECT_EQ(overloads[1].Outputs[0].GlslType, "vec4");

    EXPECT_TRUE(ReadTaggedFunctionOverloads(source, "SG_Sam").empty())
        << "a base name that is only a prefix of real functions matches nothing";
}

// The real library: SampleTexture2D's def must carry its own two overloads
// (sampler2D + the GE_MaterialTexture bridge) with the full 2-in/6-out
// signature — and must NOT contain SampleTexture2DLOD's 3-input signature,
// which the old prefix-substring matcher leaked in while the per-line reader
// dropped the real (wrapped) ones.
TEST(ShaderGraphCompilerTests, SampleTexture2DDefCarriesItsOwnOverloadsOnly)
{
    const std::filesystem::path nodesRoot = GetEngineGraphNodesRoot();
    if (!std::filesystem::exists(nodesRoot / "Sampling" / "Texture.glsl"))
        GTEST_SKIP() << "Sampling/Texture.glsl not present under " << nodesRoot.string();

    const SgNodeLibraryIndex index = SgNodeReflector::BuildIndex(nodesRoot, {});
    const auto it = index.NodesByType.find("SampleTexture2D");
    ASSERT_NE(it, index.NodesByType.end());
    ASSERT_EQ(it->second.Overloads.size(), 2u);
    for (const auto& o : it->second.Overloads)
    {
        EXPECT_EQ(o.Inputs.size(), 2u) << "a 3-input entry is the LOD signature leaking in";
        EXPECT_EQ(o.Outputs.size(), 6u) << "rgba/rgb/r/g/b/a";
    }
    EXPECT_EQ(it->second.Overloads[0].Inputs[0].GlslType, "sampler2D")
        << "front overload feeds the editor palette ports";
    EXPECT_EQ(it->second.Overloads[1].Inputs[0].GlslType, "GE_MaterialTexture");

    const auto lodIt = index.NodesByType.find("SampleTexture2DLOD");
    ASSERT_NE(lodIt, index.NodesByType.end());
    ASSERT_EQ(lodIt->second.Overloads.size(), 2u);
    for (const auto& o : lodIt->second.Overloads)
    {
        EXPECT_EQ(o.Inputs.size(), 3u);
        EXPECT_EQ(o.Outputs.size(), 1u);
    }
}

