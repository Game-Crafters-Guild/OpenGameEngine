// The Time port is one graph node with two meanings. In the vertex stage it is the endpoint's
// deformation clock — the value the adapter stamped into the InstanceData argument — so the
// same ModifyVertex can run at a second endpoint. A fragment has no endpoint and keeps the
// per-view clock.
TEST(ShaderGraphCompilerTests, TimeIsTheEndpointClockInTheVertexStageAndTheGlobalClockInTheFragmentStage)
{
    SgGraphDocument doc;
    doc.GraphName = "TimeBothStages";
    doc.Nodes.push_back({"in", "EngineInput", 0.f, 0.f, {}});
    doc.Nodes.push_back({"out", "SurfaceOutput", 200.f, 0.f, {}});
    doc.Nodes.push_back({"vout", "VertexOutput", 200.f, 200.f, {}});
    doc.Edges.push_back({"in", "Time", "vout", "PositionOffset"});
    doc.Edges.push_back({"in", "Time", "out", "BaseColor"});

    const auto library = SgNodeReflector::BuildIndex(GetEngineGraphNodesRoot(), {});
    const auto result = SgGraphCompiler::Compile(doc, library);
    ASSERT_TRUE(result.Success) << (result.Errors.empty() ? "" : result.Errors.front().Message);

    const size_t surfaceFn = result.Body.find("SurfaceOutput EvaluateSurface(");
    const size_t vertexFn = result.Body.find("vec3 ModifyVertex(");
    ASSERT_NE(surfaceFn, std::string::npos);
    ASSERT_NE(vertexFn, std::string::npos);
    ASSERT_LT(surfaceFn, vertexFn) << "the vertex entry point is emitted after the surface one";
    const std::string surfaceBody = result.Body.substr(surfaceFn, vertexFn - surfaceFn);
    const std::string vertexBody = result.Body.substr(vertexFn);

    EXPECT_NE(vertexBody.find("inst.deformationTimeSeconds"), std::string::npos)
        << "the vertex stage must read Time from its InstanceData endpoint";
    EXPECT_EQ(vertexBody.find("Light.uTimeParams"), std::string::npos)
        << "the vertex stage must not read the per-view global clock";
    EXPECT_NE(surfaceBody.find("Light.uTimeParams.x"), std::string::npos)
        << "the fragment stage keeps the per-view clock";
    EXPECT_EQ(surfaceBody.find("deformationTimeSeconds"), std::string::npos)
        << "the fragment stage has no endpoint and no InstanceData argument";
}

