void SampleByRefsForTest(Components::AnimatorRef& animRef, uint32 skeletonId, float32 deltaTime)
{
    static PoseSampleWorkspace workspace;
    auto& clipStore = ClipStore::Instance();
    auto& skStore = SkeletonStore::Instance();

    if (animRef.ClipIndex == 0 || skeletonId == 0) return;
    auto clip = clipStore.Get(animRef.ClipIndex);
    auto* skel = skStore.Get(skeletonId);
    if (!clip || !skel || skel->BoneCount == 0) return;

    TickAnimatorRef(animRef, clipStore, deltaTime, nullptr);

    if (s_TestRuntimeId == 0 || s_TestRuntimeSkeletonId != skeletonId)
    {
        s_TestRuntimeId = skStore.CreateRuntime(skeletonId);
        s_TestRuntimeSkeletonId = skeletonId;
    }
    auto* runtime = skStore.GetRuntime(s_TestRuntimeId);
    if (!runtime) return;
    if (animRef.IsBlending())
    {
        static PoseSampleWorkspace blendFrom;
        auto prev = clipStore.Get(animRef.PrevClipIndex);
        if (prev)
        {
            SampleAnimationPose(*skel, prev.get(), animRef.PrevTime, nullptr, nullptr, blendFrom);
            SampleAnimationPose(*skel, clip.get(), animRef.Time, nullptr, nullptr, workspace);
            BlendLocalPoses(workspace, blendFrom, animRef.BlendAlpha());
            ::GameEngine::Animation::BuildPoseToSkinMatrices(
                *skel, nullptr, &runtime->CompactSkinMatrices, workspace);
            return;
        }
    }
    SampleAnimationPose(*skel, clip.get(), animRef.Time, nullptr, &runtime->CompactSkinMatrices, workspace);
}

