// Sibling sidecar path conventions used by ModelAsset::PostLoad. Mirrored
// here so the bootstrap path doesn't need a back-pointer to ModelAsset.
std::filesystem::path RigSidecarPathFor(const std::filesystem::path& modelPath)
{
    std::filesystem::path p = modelPath;
    p.replace_extension();
    p += ".humanoidrig.json";
    return p;
}

std::filesystem::path RetargetMapSidecarPath(const std::filesystem::path& tgtModelPath,
                                              const std::filesystem::path& srcModelPath)
{
    const std::string srcStem = srcModelPath.stem().string();
    const std::string tgtStem = tgtModelPath.stem().string();
    std::filesystem::path out = tgtModelPath.parent_path() /
        (srcStem + "_to_" + tgtStem + ".retargetmap.json");
    return out;
}

// Loads (or auto-imports + writes) the humanoid rig sidecar for `modelPath`.
// Returns null on failure.
//
// Identity contract: the returned rig's GUID matches what
// AssetManager.ResolveAssetGuid(sidecar) yields, AND the rig is registered
// in AssetManager.m_LoadedAssets under that GUID. This is required so the
// retarget map can persist a stable rig reference and downstream consumers
// (HumanoidRetargetSystem::ResolveRig) can look the rig up via
// AssetManager.GetAsset(guid). Without registration, those lookups silently
// fail and the entity falls back to bind pose at runtime — see the post-
// bootstrap T-pose bug.
const Animation::HumanoidRig* ResolveOrAutoImportRig(
    AssetManager& assetManager,
    const Animation::SkeletonProfile& profile,
    const std::filesystem::path& modelPath,
    const Animation::SkeletonData& fallbackSkel,
    std::shared_ptr<Animation::HumanoidRig>& outOwner)
{
    if (modelPath.empty()) return nullptr;

    const std::filesystem::path sidecar = RigSidecarPathFor(modelPath);
    std::error_code ec;
    if (std::filesystem::exists(sidecar, ec) && !ec)
    {
        const GUID rigGuid = assetManager.ResolveAssetGuid(sidecar);
        if (!rigGuid.IsNull())
        {
            auto fut = assetManager.LoadAssetAsync(rigGuid, AssetLoadPriority::High);
            auto asset = std::dynamic_pointer_cast<Animation::HumanoidRig>(fut.get());
            if (asset && asset->GetState() == AssetState::Loaded)
            {
                outOwner = std::move(asset);
                // LoadAssetAsync already populated AssetManager's loaded
                // cache, so no extra registration needed.
                return outOwner.get();
            }
        }
    }

    // Auto-import path: only viable when the skeleton in question is the
    // entity's own (target). For source rigs whose model is a different
    // FBX, the sidecar must already exist (PostLoad on the source FBX
    // produces it). We log + bail in that case.
    if (fallbackSkel.BoneCount == 0) return nullptr;

    // Derive the canonical GUID from the sidecar path FIRST so the rig's
    // identity is consistent with AssetManager's registry. Without this the
    // rig was constructed with GUID() (null), the map referenced this null
    // GUID, and ResolveRig later failed.
    const GUID rigGuid = assetManager.ResolveAssetGuid(sidecar);

    auto rig = std::make_shared<Animation::HumanoidRig>(rigGuid, sidecar);
    if (!Animation::AutoImportHumanoidRig(fallbackSkel, profile, *rig))
        return nullptr;

    rig->SetAutoGenerated(true);
    rig->SetProfileRef(profile.GetGUID());

    if (!rig->SaveToPath(sidecar))
        Logger::Log::Warning(
            "[AnimationSystem] failed to write humanoid sidecar '{}'", sidecar.string());
    else
        Logger::Log::Info(
            "[AnimationSystem] HumanoidRig auto-imported via heuristic for '{}'",
            modelPath.string());

    // Publish the in-memory rig into AssetManager so GetAsset(rigGuid)
    // resolves to this same instance. Without this the retarget pipeline
    // can't recover the rig from the map's saved GUID at play time.
    if (!rigGuid.IsNull())
        assetManager.RegisterLoadedAsset(rigGuid, rig);

    outOwner = std::move(rig);
    return outOwner.get();
}

bool IsTransformAnimPath(AnimPath path)
{
    return path == AnimPath::Translation || path == AnimPath::Rotation || path == AnimPath::Scale;
}

float SampleScalarChannel(const AnimChannel& channel, float time)
{
    if (channel.keys.empty())
        return 0.0f;

    size_t hi = 0;
    while (hi < channel.keys.size() && channel.keys[hi].time < time)
        ++hi;
    size_t lo = (hi == 0) ? 0 : (hi - 1);
    if (hi >= channel.keys.size())
        hi = channel.keys.size() - 1;

    const AnimKeyframe& k0 = channel.keys[lo];
    const AnimKeyframe& k1 = channel.keys[hi];
    const float dt = k1.time - k0.time;
    const float alpha = (dt > 0.0f) ? std::clamp((time - k0.time) / dt, 0.0f, 1.0f) : 0.0f;
    const AnimInterp segInterp = k0.hasSegmentInterpOverride ? k0.segmentInterp : channel.interp;
    if (segInterp == AnimInterp::Step || dt <= 0.0f)
        return k0.translation[0];
    return k0.translation[0] + (k1.translation[0] - k0.translation[0]) * alpha;
}

void ApplyMorphAnimationChannels(ECS::World& world,
                                 ECS::EntityHandle entity,
                                 const AnimationClip& clip,
                                 float time,
                                 const Components::MeshRenderer* meshRenderer,
                                 Components::MorphTargetWeights* morph)
{
    if (!meshRenderer || !morph || morph->weightCount == 0)
        return;

    const GUID modelGuid = meshRenderer->modelAssetGuid.ToGuid();
    if (modelGuid.IsNull())
        return;

    // The model comes from the engine's AssetManager; a host that never built
    // one has no model to resolve the morph targets from.
    AssetManager* assetManager = EngineCore::GetInstance().TryGetAssetManager();
    if (!assetManager)
        return;

    auto asset = assetManager->GetAsset(modelGuid);
    if (!asset)
        asset = assetManager->LoadAssetAsync(modelGuid).get();
    const auto* model = asset ? dynamic_cast<ModelAsset*>(asset.get()) : nullptr;
    if (!model || !model->IsLoaded() || meshRenderer->meshId >= model->GetMeshCount())
        return;

    const Mesh& mesh = model->GetMesh(meshRenderer->meshId);
    if (!mesh.HasMorphTargets())
        return;

    bool changed = false;
    const uint32 count = std::min<uint32>(morph->weightCount, static_cast<uint32>(mesh.MorphTargets.size()));
    for (const AnimChannel& channel : clip.GetChannels())
    {
        if (channel.path != AnimPath::MorphWeight)
            continue;
        if (channel.boneIndex != UINT32_MAX && mesh.SourceNodeIndex >= 0 &&
            channel.boneIndex != static_cast<uint32>(mesh.SourceNodeIndex))
            continue;

        for (uint32 i = 0; i < count; ++i)
        {
            const MorphTarget& target = mesh.MorphTargets[i];
            if (channel.targetNameId != 0)
            {
                const StringId targetId = target.Name.empty() ? 0u : HashStringId(target.Name);
                if (targetId != channel.targetNameId)
                    continue;
            }
            else if (!channel.targetName.empty() && channel.targetName != target.Name)
            {
                continue;
            }

            const float value = SampleScalarChannel(channel, time);
            if (std::abs(morph->weights[i] - value) > 1e-6f)
            {
                morph->weights[i] = value;
                changed = true;
            }
            break;
        }
    }

    if (changed)
    {
        ++morph->version;
        world.AddComponentImmediate(entity, *morph);
    }
}

// One line per skeleton that the GPU animation path cannot hold, naming its model.
// Once per process: the scene's animation system and the model thumbnail's each
// route the skeleton, on their own threads.
void WarnSkeletonOverGPULimitsOnce(uint32 skeletonId, const SkeletonData& skeleton)
{
    static std::mutex s_WarnedMutex;
    static std::unordered_set<uint32> s_WarnedSkeletons;
    {
        std::lock_guard<std::mutex> lock(s_WarnedMutex);
        if (!s_WarnedSkeletons.insert(skeletonId).second)
            return;
    }
    const std::string model = skeleton.SourceModelPath.empty()
        ? "skeleton " + std::to_string(skeletonId)
        : skeleton.SourceModelPath.filename().string();
    Logger::Log::Warning(
        "Skeleton of '{}' needs {} GPU bones (joints and their ancestors) and {} levels; the GPU animation "
        "path holds {} and {}, so it animates on the CPU path. Split the rig under those counts, or accept "
        "CPU sampling.",
        model, skeleton.JointClosure.size(), skeleton.JointClosureLevelCount(),
        GPUAnimationDataStore::kMaxBones, GPUAnimationDataStore::kMaxHierarchyLevels);
}

